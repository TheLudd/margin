// Section 9 as seen from the browser: the look (L), read from computed
// styles and sizes against spec/look.css.
import { expect, open, test } from './fixtures'
import { css, expectColor, expectCss, firstColor, mono, resolveColor, resolveShadowColor, sameColor, sans, stylesheetText, tokens } from './look'

const sample = '# Title\n\nA paragraph with **bold**, a [link](https://example.com/) and `code`.\n\n## Second\n\n> quoted\n\n---\n\n### Third\n\n| h | i |\n|---|---|\n| a | b |\n| c | d |\n\n#### Fourth\n\ntext\n'

test.describe('tokens', () => {
  test('L-01: the palette is defined once on :root and used nowhere as literal colours; dark scheme only', async ({ page, margin }) => {
    await page.goto(margin.url + '/')
    const root = page.locator(':root')
    for (const [name, value] of Object.entries(tokens)) {
      const prop = name === 'removed' ? '--change-removed' : `--cp-${name}`
      expect((await css(root, prop)).trim(), prop).toBe(value)
    }
    expect((await css(root, '--change-added')).trim()).toBe(tokens.code)
    expect((await css(root, '--change-modified')).trim()).toBe(tokens.warn)
    expect((await css(root, 'color-scheme')).trim()).toBe('dark')
    const text = await stylesheetText(page)
    const outsideRoot = text.replace(/:root\s*\{[^}]*\}/g, '')
    // The minifier writes transparent as #0000; that is no colour of the palette.
    const literals = (outsideRoot.match(/#[0-9a-f]{3,8}\b/gi) ?? []).filter((l) => l !== '#0000')
    expect(literals, 'literal colours outside :root').toEqual([])
  })

  test('L-02: mono for chrome and structure, sans for body text and file names', async ({ page, margin }) => {
    margin.write('a.md', sample)
    await open(page, margin, 'a.md')
    await page.keyboard.press('Control+k')
    for (const sel of ['.ProseMirror > h1', '.ProseMirror > h2', '.doc-header', '#toc', '#sidebar .brand', '#sidebar details.section summary h2', '#sidebar time', '.doc-header .badge', 'kbd', '#finder input']) {
      expect(await css(page.locator(sel).first(), 'font-family'), sel).toBe(mono)
    }
    await page.keyboard.press('Escape')
    expect(await css(page.locator('.ProseMirror > p').first(), 'font-family')).toBe(sans)
    expect(await css(page.locator('#sidebar .file-label .name').first(), 'font-family')).toBe(sans)
    await page.goto(margin.url + '/settings')
    expect(await css(page.locator('.settings input').first(), 'font-family')).toBe(mono)
  })

  test('L-03: the page background glows magenta at top left and cyan at bottom right; selection and caret are magenta; scrollbars are 8px', async ({ page, margin }) => {
    margin.write('a.md', '# A\n\n' + 'para\n\n'.repeat(120))
    await open(page, margin, 'a.md')
    const body = page.locator('body')
    await expectColor(body, 'background-color', tokens.bg)
    const image = await css(body, 'background-image')
    const gradients = image.split('radial-gradient').slice(1)
    expect(gradients).toHaveLength(2)
    sameColor(firstColor(gradients[0])[0] !== undefined ? toCss(firstColor(gradients[0])) : '', tokens.magenta, 0.1)
    sameColor(toCss(firstColor(gradients[1])), tokens.cyan, 0.08)
    expect(gradients[0]).toContain('50%')
    const selection = await page.locator('.ProseMirror > p').first().evaluate((el) => {
      const s = getComputedStyle(el, '::selection')
      return [s.backgroundColor, s.color]
    })
    sameColor(selection[0], tokens.magenta)
    sameColor(selection[1], tokens.bg)
    await expectColor(page.locator('.ProseMirror'), 'caret-color', tokens.magenta)
    // Headless Chromium hides scrollbars, so the rule is read from the stylesheet.
    const text = await stylesheetText(page)
    expect(text.replace(/\s+/g, '')).toContain('::-webkit-scrollbar{width:8px;height:8px}')
    expect(text.replace(/\s+/g, '')).toMatch(/::-webkit-scrollbar-thumb\{background:var\(--cp-line\);border-radius:4px\}/)
  })

  test('L-04: tints are color-mix of a token and transparent, and lit things glow in their own colour', async ({ page, margin }) => {
    margin.write('a.md', sample)
    await open(page, margin, 'a.md')
    const text = await stylesheetText(page)
    expect(text).toContain('color-mix(')
    expect(text.match(/#[0-9a-f]{8}\b/gi) ?? []).toEqual([])
    const brandShadow = await css(page.locator('#sidebar .brand'), 'text-shadow')
    sameColor(toCss(firstColor(brandShadow)), tokens.magenta, 0.4)
    const h1Shadow = await css(page.locator('.ProseMirror > h1'), 'text-shadow')
    sameColor(toCss(firstColor(h1Shadow)), tokens.magenta, 0.3)
  })
})

function toCss([r, g, b, a]: [number, number, number, number]): string {
  return `rgba(${r}, ${g}, ${b}, ${a})`
}

