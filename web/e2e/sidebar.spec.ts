// Section 5 as seen from the browser: the sidebar (S) and the finder, with
// the F-03, F-04, W-01 and W-06 checks that need them.
import { expect, older, open, recent, sidebarLink, test } from './fixtures'

test.describe('sidebar', () => {
  test('S-01, S-03, S-02: a file opened in margin is in Recent as viewed; a change on disk after that makes it modified and unread', async ({ page, margin }) => {
    margin.write('notes/a.md', '# A\n\ntext\n')
    await page.goto(margin.url + '/')
    await expect(recent(page).locator('.empty')).toHaveText('Nothing in the last 14 days')
    await open(page, margin, 'notes/a.md')
    const link = sidebarLink(page, '/code/notes/a.md')
    await expect(recent(page).locator('a[href="/code/notes/a.md"]')).toHaveCount(1)
    await expect(link.locator('time')).toHaveText('now')
    await expect(link).not.toHaveClass(/unread/)
    margin.write('notes/a.md', '# A\n\nchanged outside\n')
    await expect(link).toHaveClass(/unread/)
    await expect(link.locator('time')).toHaveClass(/modified/)
    await expect(recent(page).locator('summary .count')).toHaveText('1')
  })

  test('S-02, S-01: a file an LLM just wrote sits under Older until it is opened, however new', async ({ page, margin }) => {
    margin.write('old/stale.md', '# Old\n')
    await page.goto(margin.url + '/')
    margin.write('fresh/new.md', '# New\n')
    const group = older(page).locator('details[data-project="fresh"]')
    await expect(group).toHaveCount(1)
    await expect(recent(page).locator('a')).toHaveCount(0)
    await group.locator('summary').click()
    await expect(group.locator('a[href="/code/fresh/new.md"]')).not.toHaveClass(/unread/)
  })

  test('S-02: equal content written again is not a modification', async ({ page, margin }) => {
    margin.write('a.md', 'same\n')
    await open(page, margin, 'a.md')
    const link = recent(page).locator('a[href="/code/a.md"]')
    await expect(link).toHaveCount(1)
    margin.writeAtomic('a.md', 'same\n')
    await page.waitForTimeout(500)
    await expect(link).not.toHaveClass(/unread/)
  })

  test('S-03: views survive a restart', async ({ page, margin }) => {
    margin.write('a.md', '# A\n')
    await open(page, margin, 'a.md')
    await expect(recent(page).locator('a[href="/code/a.md"]')).toHaveCount(1)
    await margin.restart()
    await page.goto(margin.url + '/')
    await expect(recent(page).locator('a[href="/code/a.md"]')).toHaveCount(1)
  })

  test('S-04: Recent and Older fold with counts, project groups fold, and the state survives a reload', async ({ page, margin }) => {
    margin.write('alpha/a.md', '# A\n')
    margin.write('alpha/b.md', '# B\n')
    margin.write('beta/c.md', '# C\n')
    await page.goto(margin.url + '/')
    const olderSection = older(page)
    await expect(olderSection.locator('> summary .count')).toHaveText('3')
    const alpha = olderSection.locator('details[data-project="alpha"]')
    const beta = olderSection.locator('details[data-project="beta"]')
    await expect(alpha.locator('summary .count')).toHaveText('2')
    await expect(alpha).not.toHaveAttribute('open')
    await alpha.locator('summary').click()
    await expect(alpha).toHaveAttribute('open', '')
    await expect(alpha.locator('li a .name').nth(0)).toHaveText('a.md')
    await expect(alpha.locator('li a .name').nth(1)).toHaveText('b.md')
    await recent(page).locator('> summary').click()
    await expect(recent(page)).not.toHaveAttribute('open')
    await page.reload()
    await expect(olderSection.locator('details[data-project="alpha"]')).toHaveAttribute('open', '')
    await expect(beta).not.toHaveAttribute('open')
    await expect(recent(page)).not.toHaveAttribute('open')
  })

  test('S-04: Older and its groups stay as they were when a file is opened from them', async ({ page, margin }) => {
    margin.write('alpha/a.md', '# A\n')
    margin.write('alpha/b.md', '# B\n')
    margin.write('beta/c.md', '# C\n')
    await page.goto(margin.url + '/')
    const alpha = older(page).locator('details[data-project="alpha"]')
    await alpha.locator('summary').click()
    await alpha.locator('a[href="/code/alpha/a.md"]').click()
    await expect(page.locator('#main')).toHaveAttribute('data-view', 'document')
    await expect(recent(page).locator('a[href="/code/alpha/a.md"]')).toHaveCount(1)
    await expect(older(page)).toHaveAttribute('open', '')
    await expect(alpha).toHaveAttribute('open', '')
    await expect(older(page).locator('details[data-project="beta"]')).not.toHaveAttribute('open')
  })

  test('S-05: the × on a Recent entry forgets its view, survives a restart, and a later change shows the file again', async ({ page, margin }) => {
    margin.write('a.md', '# A\n')
    await open(page, margin, 'a.md')
    const entry = recent(page).locator('li.recent-entry', { has: page.locator('a[href="/code/a.md"]') })
    await expect(entry).toHaveCount(1)
    await entry.hover()
    await expect(entry.locator('button.forget')).toBeVisible()
    await entry.locator('button.forget').click()
    await expect(recent(page).locator('a[href="/code/a.md"]')).toHaveCount(0)
    await expect(older(page).locator('a[href="/code/a.md"]')).toHaveCount(1)
    await margin.restart()
    await page.goto(margin.url + '/')
    await expect(recent(page).locator('a[href="/code/a.md"]')).toHaveCount(0)
    await page.waitForTimeout(1100)
    margin.write('a.md', '# A\n\nchanged\n')
    await expect(recent(page).locator('a[href="/code/a.md"]')).toHaveClass(/unread/)
  })

  test('S-06: the lists refresh on events and on reconnect, and never on a timer', async ({ page, margin }) => {
    margin.write('a.md', '# A\n')
    await page.goto(margin.url + '/')
    await expect(older(page).locator('> summary .count')).toHaveText('1')
    let requests = 0
    page.on('request', (r) => {
      if (r.url().endsWith('/api/lists')) requests++
    })
    await page.waitForTimeout(3000)
    expect(requests).toBe(0)
    margin.write('b.md', '# B\n')
    await expect(older(page).locator('> summary .count')).toHaveText('2')
    expect(requests).toBeGreaterThan(0)
    await margin.stop()
    margin.write('c.md', '# C\n')
    await margin.restart()
    await expect(older(page).locator('> summary .count')).toHaveText('3', { timeout: 15_000 })
  })

  test('S-06: the lists refresh when the tab becomes visible', async ({ page, margin }) => {
    margin.write('a.md', '# A\n')
    await page.goto(margin.url + '/')
    await expect(older(page).locator('> summary .count')).toHaveText('1')
    let requests = 0
    page.on('request', (r) => {
      if (r.url().endsWith('/api/lists')) requests++
    })
    await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')))
    await expect.poll(() => requests).toBe(1)
  })

  test('S-07: files with unread changes get the mark by their time, by their copy count, or at the right edge', async ({ page, margin }) => {
    margin.write('a.md', '# A\n')
    margin.write('b.md', '# B\n')
    await open(page, margin, 'a.md')
    await open(page, margin, 'b.md')
    margin.write('a.md', '# A changed\n')
    const link = recent(page).locator('a[href="/code/a.md"]')
    await expect(link).toHaveClass(/unread/)
    const dot = await link.locator('time').evaluate((t) => {
      const s = getComputedStyle(t, '::after')
      return { width: s.width, height: s.height, radius: s.borderRadius, color: getComputedStyle(t).color }
    })
    expect(dot.width).toBe('4px')
    expect(dot.height).toBe('4px')
    expect(dot.radius).toBe('50%')
    expect(dot.color).toBe('rgb(92, 255, 168)')
    // Dismissed, the file is under Older with no time: the mark sits at the right edge.
    const entry = recent(page).locator('li.recent-entry', { has: page.locator('a[href="/code/a.md"]') })
    await entry.hover()
    await entry.locator('button.forget').click()
    await page.waitForTimeout(1100)
    margin.write('a.md', '# A changed again\n')
    await expect(recent(page).locator('a[href="/code/a.md"]')).toHaveClass(/unread/)
  })

  test('S-08, L-07: the sidebar folds to a 48px strip and unfolds, and the fold survives a reload', async ({ page, margin }) => {
    margin.write('a.md', '# A\n')
    await page.goto(margin.url + '/')
    const sidebar = page.locator('#sidebar')
    expect((await sidebar.boundingBox())!.width).toBe(290)
    await page.locator('#sidebar .close-sidebar').click()
    expect((await sidebar.boundingBox())!.width).toBe(48)
    await expect(page.locator('#sidebar .unfold-sidebar')).toBeVisible()
    await expect(page.locator('#sidebar .brand')).toBeHidden()
    await page.reload()
    expect((await sidebar.boundingBox())!.width).toBe(48)
    await page.locator('#sidebar .unfold-sidebar').click()
    expect((await sidebar.boundingBox())!.width).toBe(290)
  })

  test('S-11: sidebar links are real links: a plain click opens in place, a middle click opens a new tab', async ({ page, margin, context }) => {
    margin.write('a.md', '# A\n')
    await page.goto(margin.url + '/')
    await page.evaluate(() => {
      ;(window as unknown as { marker: string }).marker = 'kept'
    })
    const group = older(page).locator('details[data-project="code"]')
    await group.locator('summary').click()
    const link = group.locator('a[href="/code/a.md"]')
    await expect(link).toHaveAttribute('href', '/code/a.md')
    const [popup] = await Promise.all([context.waitForEvent('page'), link.click({ button: 'middle' })])
    await popup.waitForLoadState()
    expect(popup.url()).toBe(margin.url + '/code/a.md')
    await popup.close()
    await link.click()
    await expect(page).toHaveURL(margin.url + '/code/a.md')
    await expect(page.locator('#main')).toHaveAttribute('data-view', 'document')
    expect(await page.evaluate(() => (window as unknown as { marker?: string }).marker)).toBe('kept')
  })

  test('F-03, F-04: with a single root the folder is shown without the root name; with two, with it; URLs keep it', async ({ page, margin }) => {
    margin.write('margin/plan.md', '# Plan\n')
    await page.goto(margin.url + '/')
    const group = older(page).locator('details[data-project="margin"]')
    await group.locator('summary').click()
    const link = group.locator('a[href="/code/margin/plan.md"]')
    await expect(link.locator('.file-label .name')).toHaveText('plan.md')
    await expect(link.locator('.file-label .dir')).toHaveText('margin')
    margin.writeConfig({ roots: [{ name: 'code', path: '~/code' }, { name: 'home', path: '~/.config' }] })
    const link2 = older(page).locator('details[data-project="code/margin"] a[href="/code/margin/plan.md"]')
    await expect(link2).toHaveCount(1)
    await older(page).locator('details[data-project="code/margin"] summary').click()
    await expect(link2.locator('.file-label .dir')).toHaveText('code/margin')
  })

  test('F-01, F-02: ignored, excluded, .git and node_modules files are not listed', async ({ page, margin }) => {
    margin.repo('repo', { 'readme.md': '# R\n', '.gitignore': 'build/\n' })
    margin.write('repo/build/out.md', 'built')
    margin.write('repo/node_modules/pkg/readme.md', 'nm')
    margin.write('repo/CHANGELOG.md', 'c')
    margin.writeConfig({ roots: [{ name: 'code', path: '~/code' }], exclude: ['CHANGELOG.md'] })
    await page.goto(margin.url + '/')
    const group = older(page).locator('details[data-project="repo"]')
    await expect(group.locator('summary .count')).toHaveText('1')
    await group.locator('summary').click()
    await expect(group.locator('a .name')).toHaveText(['readme.md'])
  })

  test('W-01, W-06: a file in several worktrees is listed once with a copy count, updated about a second after a change', async ({ page, margin }) => {
    margin.repo('foo/main', { 'readme.md': '# R\n', 'docs/guide.md': '# G\n' })
    margin.git('foo/main', 'worktree', 'add', '-q', '-b', 'feat', '../feat')
    await page.goto(margin.url + '/')
    const group = older(page).locator('details[data-project="foo"]')
    await expect(group.locator('summary .count')).toHaveText('2')
    await group.locator('summary').click()
    const guide = group.locator('li', { has: page.locator('a .name', { hasText: 'guide.md' }) })
    await expect(guide).toHaveCount(1)
    await expect(guide.locator('.copies')).toHaveText('×2')
    await expect(guide.locator('.copies')).not.toHaveClass(/changed/)
    await expect(guide.locator('a')).toHaveAttribute('href', '/code/foo/main/docs/guide.md')
    await expect(guide.locator('.file-label .dir')).toHaveText('foo/docs')
    margin.write('foo/feat/docs/guide.md', '# G changed in feat\n')
    await expect(guide.locator('.copies')).toHaveClass(/changed/, { timeout: 5000 })
    await expect(guide.locator('a')).toHaveAttribute('href', '/code/foo/feat/docs/guide.md')
  })
})

test.describe('finder', () => {
  test.beforeEach(({ margin }) => {
    for (let i = 0; i < 12; i++) margin.write(`notes/note-${String(i).padStart(2, '0')}.md`, `# ${i}\n`)
    margin.write('margin/guarded-commands-plan.md', '# GCP\n')
    margin.write('margin/plan.md', '# Plan\n')
  })

  test('S-09, K: Ctrl K and Ctrl P open the finder; an empty query lists recent activity; click outside closes', async ({ page, margin }) => {
    await open(page, margin, 'margin/plan.md')
    await page.keyboard.press('Control+k')
    const finder = page.locator('#finder')
    await expect(finder).toBeVisible()
    await expect(finder.locator('li.tier').first()).toHaveText('Recent')
    await expect(finder.locator('li.row a[href="/code/margin/plan.md"]')).toHaveCount(1)
    await page.mouse.click(5, 5)
    await expect(finder).toBeHidden()
    await page.keyboard.press('Control+p')
    await expect(finder).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(finder).toBeHidden()
    await page.locator('#sidebar .find').click()
    await expect(finder).toBeVisible()
  })

  test('S-09, S-10: a query searches active files only; Tab adds Older; sections show their best 10 and say n of m', async ({ page, margin }) => {
    for (let i = 0; i < 12; i++) await open(page, margin, `notes/note-${String(i).padStart(2, '0')}.md`)
    await page.keyboard.press('Control+k')
    const finder = page.locator('#finder')
    await expect(finder.locator('li.tier').first()).toHaveText('Recent · 10 of 12')
    await expect(finder.locator('li.row')).toHaveCount(10)
    await expect(finder.locator('li.toggle')).toHaveText('Tab · 2 older files')
    await finder.locator('input').fill('gcp')
    await expect(finder.locator('li.none')).toHaveText('No recent file matches')
    await expect(finder.locator('li.toggle')).toHaveText('Tab · 1 older file')
    await page.keyboard.press('Tab')
    await expect(finder.locator('li.tier.older')).toHaveText('Older')
    await expect(finder.locator('li.row.older a[href="/code/margin/guarded-commands-plan.md"]')).toHaveCount(1)
    await finder.locator('input').fill('note')
    await expect(finder.locator('li.tier').first()).toHaveText('Recent · 10 of 12')
    await finder.locator('li.toggle').click()
    await expect(finder.locator('li.tier.older')).toHaveCount(0)
  })

  test('S-09, K: arrows move, Enter opens', async ({ page, margin }) => {
    await open(page, margin, 'margin/plan.md')
    await page.waitForTimeout(1100)
    await open(page, margin, 'margin/guarded-commands-plan.md')
    await page.keyboard.press('Control+k')
    const finder = page.locator('#finder')
    await expect(finder.locator('li.row').nth(0)).toHaveClass(/selected/)
    await page.keyboard.press('ArrowDown')
    await expect(finder.locator('li.row').nth(1)).toHaveClass(/selected/)
    await page.keyboard.press('ArrowUp')
    await expect(finder.locator('li.row').nth(0)).toHaveClass(/selected/)
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter')
    await expect(finder).toBeHidden()
    await expect(page).toHaveURL(margin.url + '/code/margin/plan.md')
  })

  test('S-10, F-04, W-01: matches in the name rank above folders, rows show the file label, and copies count once', async ({ page, margin }) => {
    margin.repo('foo/main', { 'readme.md': '# R\n' })
    margin.git('foo/main', 'worktree', 'add', '-q', '-b', 'feat', '../feat')
    await open(page, margin, 'margin/plan.md')
    await page.keyboard.press('Control+k')
    const finder = page.locator('#finder')
    await finder.locator('input').fill('plan')
    await page.keyboard.press('Tab')
    const rows = finder.locator('li.row a .name')
    await expect(rows.first()).toHaveText('plan.md')
    await expect(finder.locator('li.row a[href="/code/margin/plan.md"] .file-label .dir')).toHaveText('margin')
    await finder.locator('input').fill('readme')
    await expect(finder.locator('li.row.older')).toHaveCount(1)
    await expect(finder.locator('li.row.older .copies')).toHaveText('×2')
  })
})
